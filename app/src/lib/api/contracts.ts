import { z } from "zod";

export const MAX_VIDEO_BYTES = 100 * 1024 * 1024;
export const POLL_INTERVAL_MS = 2_000;
export const PROCESSING_DEADLINE_MS = 300_000;
export const DEFAULT_PAGE_SIZE = 20;
export const MAX_PAGE_SIZE = 100;

export const ResourceIdSchema = z
	.string()
	.min(1)
	.max(128)
	.regex(/^[A-Za-z0-9_-]+$/);
export const JobIdSchema = ResourceIdSchema.describe(
	"Opaque, case-sensitive job ID; not necessarily a UUID.",
);
export const TextSchema = z.string().min(1).regex(/\S/);
export const TimestampSchema = z
	.number()
	.nonnegative()
	.describe("Seconds from the original video start.");
export const AnalyzeAcceptedSchema = z.strictObject({ job_id: JobIdSchema });
export const JobViewSchema = z.enum(["jury", "ui"]).default("jury");

export const AnalysisFailureSchema = z.strictObject({
	code: z.enum([
		"VIDEO_UNREADABLE",
		"PROCESSING_TIMEOUT",
		"ANALYSIS_FAILED",
		"OVERVIEW_GENERATION_FAILED",
	]),
	message: TextSchema,
});

const stageFields = {
	id: ResourceIdSchema.describe(
		"Backend-defined stage ID, stable within the job; not a frontend enum.",
	),
	label: TextSchema.describe("Backend-provided display label."),
	description: TextSchema.describe(
		"What this stage does, suitable for the user.",
	),
};
export const StageSchema = z.discriminatedUnion("status", [
	z.strictObject({
		...stageFields,
		status: z.literal("pending"),
		percent: z.literal(0),
	}),
	z.strictObject({
		...stageFields,
		status: z.literal("running"),
		percent: z.number().min(0).lt(100),
	}),
	z.strictObject({
		...stageFields,
		status: z.literal("done"),
		percent: z.literal(100),
	}),
	z.strictObject({
		...stageFields,
		status: z.literal("failed"),
		percent: z.number().min(0).lt(100),
	}),
]);
export const ProgressSchema = z.strictObject({
	percent: z
		.number()
		.min(0)
		.max(100)
		.describe(
			"Backend-calculated overall work completion, not model confidence or elapsed time.",
		),
	stages: z
		.array(StageSchema)
		.min(1)
		.describe(
			"Ordered execution plan supplied by the backend; stage IDs and order stay stable for this job.",
		),
});

export const OverviewSchema = z.strictObject({
	summary: TextSchema.describe(
		"Short plain-text overview of the verdict, generated by the local LLM from validated analysis results.",
	),
	limitations: z
		.array(TextSchema)
		.describe(
			"Observed visibility or coverage limitations; empty when none are identified. Not an alternative verdict.",
		),
});

export const ProcessingJobSchema = z.strictObject({
	job_id: JobIdSchema,
	status: z.literal("processing"),
	progress: ProgressSchema.extend({ percent: z.number().min(0).lt(100) }),
});
export const FailedJobSchema = z.strictObject({
	job_id: JobIdSchema,
	status: z.literal("failed"),
	progress: ProgressSchema.extend({ percent: z.number().min(0).lt(100) }),
	error: AnalysisFailureSchema,
});
const completedFields = {
	job_id: JobIdSchema,
	status: z.literal("done"),
	progress: ProgressSchema.extend({ percent: z.literal(100) }),
	overview: OverviewSchema,
};
export const NoViolationJobSchema = z.strictObject({
	...completedFields,
	verdict: z.literal("no_violation"),
	violations_count: z.literal(0),
});
export const ViolationJobSchema = z.strictObject({
	...completedFields,
	verdict: z.literal("violation"),
	violations_count: z.int().positive(),
});

function validateProgress(
	job: { status: string; progress: z.infer<typeof ProgressSchema> },
	ctx: z.RefinementCtx,
) {
	const stages = job.progress.stages;
	const ids = stages.map((stage) => stage.id);
	const running = stages.filter((stage) => stage.status === "running").length;
	const failed = stages.filter((stage) => stage.status === "failed").length;
	// Sequential execution: completed prefix, optional active stage, pending suffix.
	const ranks = stages.map((stage) =>
		stage.status === "done" ? 0 : stage.status === "pending" ? 2 : 1,
	);
	const ordered = ranks.every(
		(rank, index) => index === 0 || rank >= ranks[index - 1],
	);
	const done = stages.every((stage) => stage.status === "done");
	const validState =
		job.status === "done"
			? done
			: job.status === "failed"
				? failed === 1 && running === 0
				: failed === 0 && running <= 1 && !done;
	const allPending = stages.every((stage) => stage.status === "pending");
	if (
		new Set(ids).size !== ids.length ||
		!ordered ||
		!validState ||
		(allPending && job.progress.percent !== 0)
	) {
		ctx.addIssue({
			code: "custom",
			path: ["progress"],
			message: "Invalid stage plan or progress for this job state.",
		});
	}
}

export const CompletedJobSchema = z
	.discriminatedUnion("verdict", [NoViolationJobSchema, ViolationJobSchema])
	.superRefine(validateProgress);
export const JobResponseSchema = z
	.discriminatedUnion("status", [
		ProcessingJobSchema,
		CompletedJobSchema,
		FailedJobSchema,
	])
	.superRefine(validateProgress);

export const NormativeSourceSchema = z.strictObject({
	document_title: TextSchema,
	section: TextSchema.nullable().describe(
		"Exact clause/section, or null when unavailable, as allowed by the case FAQ.",
	),
	url: z.url().regex(/^https?:\/\//),
});
export const RuleSchema = z.strictObject({
	text: TextSchema.describe("Requirement supported by the cited sources."),
	sources: z.array(NormativeSourceSchema).min(1),
});
export const ViolationDetailsSchema = z.strictObject({
	type: TextSchema.describe(
		"Human-readable event type; no closed taxonomy is specified by the case.",
	),
	timecode_sec: TimestampSchema,
	description: TextSchema.describe(
		"What is visible and why it may indicate a violation; no claims about unseen data.",
	),
});
export const EvidenceFrameSchema = z
	.strictObject({
		frame_id: ResourceIdSchema,
		timestamp_sec: TimestampSchema,
	})
	.describe(
		"Frame reference. Fetch JPEG bytes separately through the authenticated frame endpoint; no inline image data.",
	);
export const ViolationSchema = ViolationDetailsSchema.extend({
	id: ResourceIdSchema.describe(
		"Stable event ID, unique within this job and across its pages.",
	),
	rule: RuleSchema,
	evidence_frames: z.array(EvidenceFrameSchema).min(1).max(3),
});

export const PaginationQuerySchema = z
	.strictObject({
		page: z.int().min(1).max(1_000_000).default(1),
		page_size: z.int().min(1).max(MAX_PAGE_SIZE).default(DEFAULT_PAGE_SIZE),
	})
	.describe(
		"HTTP query parameters are decimal integers, parsed by the server; malformed or repeated values return 400.",
	);
export const ViolationsPageSchema = z
	.strictObject({
		job_id: JobIdSchema,
		items: z.array(ViolationSchema).max(MAX_PAGE_SIZE),
		page: z.int().min(1).max(1_000_000),
		page_size: z.int().min(1).max(MAX_PAGE_SIZE),
		total: z
			.int()
			.nonnegative()
			.describe(
				"Total events in the immutable completed result, not the current page length.",
			),
	})
	.superRefine((page, ctx) => {
		const expected = Math.min(
			page.page_size,
			Math.max(0, page.total - (page.page - 1) * page.page_size),
		);
		const ids = page.items.map((item) => item.id);
		const ordered = page.items.every((item, index) => {
			if (index === 0) return true;
			const previous = page.items[index - 1];
			return (
				item.timecode_sec > previous.timecode_sec ||
				(item.timecode_sec === previous.timecode_sec && item.id > previous.id)
			);
		});
		if (
			page.items.length !== expected ||
			new Set(ids).size !== ids.length ||
			!ordered
		) {
			ctx.addIssue({
				code: "custom",
				path: ["items"],
				message:
					"Page must have the expected number of unique events, ordered by (timecode_sec, id).",
			});
		}
		page.items.forEach((item, index) => {
			if (
				new Set(item.evidence_frames.map((frame) => frame.frame_id)).size !==
				item.evidence_frames.length
			) {
				ctx.addIssue({
					code: "custom",
					path: ["items", index, "evidence_frames"],
					message: "Frame IDs must be unique within the event.",
				});
			}
		});
	});
// Client composition, not an HTTP response. The page changes independently of the overview.
export const CompletedReviewSchema = z
	.strictObject({ job: CompletedJobSchema, page: ViolationsPageSchema })
	.superRefine(({ job, page }, ctx) => {
		if (job.job_id !== page.job_id || job.violations_count !== page.total) {
			ctx.addIssue({
				code: "custom",
				path: ["page"],
				message:
					"Page must belong to this job and have the same total event count.",
			});
		}
	});

